  "recurring-autopay-mandates",
  "payment-policies",
  "payment-policies-timezone",
  "payment-intents",
  "payment-intents-cancelled",
  // Workspaces are no longer a feature and nothing creates one, but the
  // tables stay until the code stops reading them: /api/onboarding (loaded
  // on every page by WorkspaceProvider) fails without `workspaces`, and
  // account-business's cleanup block references it.
  "business-workspaces",
  "account-business",
  "business-profile-details",
  "business-verification-reviews",
  "business-payroll",
  "earn-vault",
  "referral-and-swiftpoints",
  "referral-progress-payments",
  "swiftpoints-economy-and-auto-deposit",
  "swiftpoints-entitlement-term",
  "swiftpoints-payroll-feature",
  "swiftpoints-and-auto-deposit-rls",
  "swift-circle",
